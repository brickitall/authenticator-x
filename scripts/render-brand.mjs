const cssText = css();
const texts = {
  'brand.css': cssText,
  'guide.html': guide(cssText),
  ...Object.fromEntries(Object.entries(SVGS).map(([name, make]) => [`assets/${name}`, `${make()}\n`])),
};

let stale = 0;
for (const [path, content] of Object.entries(texts)) {
  const file = join(OUT, path);
  if (CHECK) {
    let current = null;
    try {
      current = readFileSync(file, 'utf8');
    } catch {}
    if (current !== content) {
      console.error(`✗ ${relative(ROOT, file)} is stale — run node scripts/render-brand.mjs`);
      stale++;
    }
    continue;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log(`✓ ${relative(ROOT, file)}`);
}

if (CHECK) {
  if (stale) process.exit(1);
  console.log('✓ brand kit is current');
} else {
  for (const [name, make] of Object.entries(PNGS)) {
    const file = join(OUT, 'assets', name);
    writeFileSync(file, make());
    console.log(`✓ ${relative(ROOT, file)}`);
  }
}
