/**
 * Writes Keyrook's identity kit from packages/brand/src — the one source every
 * Keyrook product takes its look from.
 *
 *   node scripts/render-brand.mjs           → packages/brand/{brand.css,assets/,guide.html}
 *   node scripts/render-brand.mjs --check   fails if any text output is stale (CI)
 *
 * brand.css is the tokens as CSS custom properties plus the hand-drawn
 * motions, for any page to import. assets/ is the logo kit as SVG and PNG.
 * guide.html is the brand book: what each piece is for, and what not to do.
 * The PNGs are left out of --check: zlib output may differ between Node
 * versions, and they are drawn from the same geometry as the SVGs beside them.
 */
