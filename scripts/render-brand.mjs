function css() {
  const lines = [HEADER, '', ':root {'];
  const v = (name, value) => lines.push(`  --kr-${name}: ${value};`);
  v('ink', INK);
  v('paper', PAPER);
  for (const [stop, hex] of Object.entries(NEUTRAL)) v(`neutral-${stop}`, hex);
  for (const [name, ramp] of Object.entries(CRAYON)) {
    for (const [stop, hex] of Object.entries(ramp)) v(`${name}-${stop}`, hex);
  }
  v('font-sans', FONT.sans);
  v('font-mono', FONT.mono);
  for (const [name, px] of Object.entries(LINE)) v(`line-${name}`, `${px}px`);
  v('radius-sketch', SKETCH_RADIUS);
  v('radius-sketch-small', SKETCH_RADIUS_SMALL);
  for (const name of ['fast', 'base', 'slow', 'draw']) v(`motion-${name}`, `${MOTION[name]}ms`);
  v('boil-step', `${MOTION.boilStep}ms`);
  v('boil-rounds', String(MOTION.boilRounds));
  v('ease-out', MOTION.easeOut);
  lines.push('');
  lines.push('  /* What a page reads. Light by default; dark below. */');
  const light = {
    page: 'var(--kr-paper)',
    surface: 'var(--kr-neutral-0)',
    text: 'var(--kr-ink)',
    'text-muted': 'var(--kr-neutral-600)',
    line: 'var(--kr-neutral-200)',
    'crow-ink': 'var(--kr-ink)',
  };
  const dark = {
    page: `var(--kr-neutral-950)`,
    surface: 'var(--kr-neutral-900)',
    text: 'var(--kr-paper)',
    'text-muted': 'var(--kr-neutral-400)',
    line: 'var(--kr-neutral-700)',
    'crow-ink': 'var(--kr-paper)',
  };
  for (const [role, { crayon, light: stop }] of Object.entries(ROLES)) light[role] = `var(--kr-${crayon}-${stop})`;
  for (const [role, { crayon, dark: stop }] of Object.entries(ROLES)) dark[role] = `var(--kr-${crayon}-${stop})`;
  for (const [name, value] of Object.entries(light)) v(name, value);
  lines.push('}', '');
  const darkBlock = (indent) =>
    Object.entries(dark).map(([name, value]) => `${indent}--kr-${name}: ${value};`);
  // Two ways in: an explicit attribute, which wins (an app's own theme
  // switch), and the system setting when a page has none.
  lines.push("[data-theme='dark'] {", ...darkBlock('  '), '}', '');
  lines.push('@media (prefers-color-scheme: dark) {', "  :root:not([data-theme='light']) {", ...darkBlock('    '), '  }', '}', '');
  lines.push(
    '/* A drawing redrawn a hair out of place three times a second, a few times,',
    '   then still. Drawings only — never text a person must read. */',
    '.kr-boil {',
    '  animation: kr-boil calc(var(--kr-boil-step) * 3) steps(1) var(--kr-boil-rounds);',
    '}',
    '',
    '.kr-boil-loop {',
    '  animation: kr-boil calc(var(--kr-boil-step) * 3) steps(1) infinite;',
    '}',
    '',
    '@keyframes kr-boil {',
    '  0% { transform: none; }',
    '  33% { transform: rotate(-1.2deg) translate(0.4px, -0.4px); }',
    '  66% { transform: rotate(0.9deg) translate(-0.4px, 0.3px); }',
    '}',
    '',
    '/* Lines drawn in by the pen, once. Each path needs pathLength="1". */',
    '.kr-draw :is(path, circle, line, polyline) {',
    '  stroke-dasharray: 1;',
    '  stroke-dashoffset: 1;',
    '  animation: kr-draw var(--kr-motion-draw) var(--kr-ease-out) forwards;',
    '}',
    '',
    '@keyframes kr-draw {',
    '  to { stroke-dashoffset: 0; }',
    '}',
    '',
    '/* A box drawn by hand. Pair with a border in var(--kr-line-pen). */',
    '.kr-sketch {',
    '  border-radius: var(--kr-radius-sketch);',
    '}',
    '',
    '.kr-sketch-small {',
    '  border-radius: var(--kr-radius-sketch-small);',
    '}',
    '',
    '@media (prefers-reduced-motion: reduce) {',
    '  .kr-boil,',
    '  .kr-boil-loop,',
    '  .kr-draw :is(path, circle, line, polyline) {',
    '    animation: none;',
    '    stroke-dashoffset: 0;',
    '  }',
    '}',
    '',
  );
  return lines.join('\n');
}

